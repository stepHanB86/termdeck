const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('deck', {
  createPty: (opts) => ipcRenderer.invoke('pty:create', opts),
  write: (id, data) => ipcRenderer.send('pty:write', id, data),
  resize: (id, cols, rows) => ipcRenderer.send('pty:resize', id, cols, rows),
  kill: (id) => ipcRenderer.send('pty:kill', id),
  cwd: (id) => ipcRenderer.invoke('pty:cwd', id),
  onData: (fn) => ipcRenderer.on('pty:data', (_e, id, data) => fn(id, data)),
  onExit: (fn) => ipcRenderer.on('pty:exit', (_e, id) => fn(id)),
  clipWrite: (text, type) => ipcRenderer.send('clip:write', text, type),
  clipRead: (type) => ipcRenderer.invoke('clip:read', type),
  clipImage: () => ipcRenderer.invoke('clip:image'),
  pathForFile: (file) => { try { return webUtils.getPathForFile(file) || ''; } catch { return ''; } },
  saveDrop: (name, bytes) => ipcRenderer.invoke('drop:save', name, bytes),
  saveDropUrl: (url) => ipcRenderer.invoke('drop:url', url),
  onAiStatus: (fn) => ipcRenderer.on('ai:status', (_e, s) => fn(s)),
  takeoverList: () => ipcRenderer.invoke('takeover:list'),
  takeoverClaude: (pid, wait) => ipcRenderer.invoke('takeover:claude', { pid, wait }),
  takeoverCancel: (pid) => ipcRenderer.send('takeover:cancel', pid),
  takeoverShell: (pid, close) => ipcRenderer.invoke('takeover:shell', { pid, close }),
  hold: (id) => ipcRenderer.invoke('pty:hold', id),
  detach: (id, payload) => ipcRenderer.send('pty:detach', id, payload),
  dock: (id, payload) => ipcRenderer.send('pty:dock', id, payload),
  singleInit: (id) => ipcRenderer.invoke('single:init', id),
  adoptInit: (id) => ipcRenderer.invoke('adopt:init', id),
  onAdopt: (fn) => ipcRenderer.on('pty:adopt', (_e, id, payload) => fn(id, payload)),
  removeAccount: (key) => ipcRenderer.invoke('accounts:remove', key),
  renameAccount: (key, label) => ipcRenderer.invoke('accounts:rename', key, label),
  getLimits: (force) => ipcRenderer.invoke('limits:get', force),
  onLimits: (fn) => ipcRenderer.on('limits', (_e, l) => fn(l)),
  setTitle: (t) => ipcRenderer.send('win:title', t),
  toggleFullscreen: () => ipcRenderer.send('win:fullscreen'),
  saveSession: (state) => ipcRenderer.send('session:save', state),
  loadSession: () => ipcRenderer.invoke('session:load'),
});
